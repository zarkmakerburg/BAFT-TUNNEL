// Regenerates src/worldmap.ts from Natural Earth land (public domain) via world-atlas 2.0.2 (ISC).
// Usage: node scripts/gen-worldmap.mjs /path/to/dir/with/node_modules(world-atlas,topojson-client)
// Build-time only: the panel ships the resulting path as a constant; no map tiles, no network at runtime.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/gen-worldmap.mjs DIR'); process.exit(1); }
const req = createRequire(dir + '/');
const { feature } = req('topojson-client');
const topo = JSON.parse(readFileSync(dir + '/node_modules/world-atlas/land-110m.json', 'utf8'));
const land = feature(topo, topo.objects.land);
const S = 2, TOP = 84, BOT = -58;             // 2 units per degree, latitude crop
const W = 360 * S, H = (TOP - BOT) * S;
const px = (lon) => Math.round((lon + 180) * S), py = (lat) => Math.round((TOP - Math.max(BOT, Math.min(TOP, lat))) * S);
let d = '';
for (const g of land.features ? land.features.flatMap((f) => f.geometry.coordinates) : land.geometry.coordinates) {
  for (const ring of g) {
    let px0 = 0, py0 = 0, first = true, n = 0;
    for (const [lon, lat] of ring) {
      const x = px(lon), y = py(lat);
      if (first) { d += `M${x} ${y}`; first = false; n = 1; }
      else if (x !== px0 || y !== py0) { d += `l${x - px0} ${y - py0}`; n++; }
      px0 = x; py0 = y;
    }
    if (n > 2) d += 'z'; else d = d.slice(0, d.lastIndexOf('M'));
  }
}
writeFileSync(new URL('../src/worldmap.ts', import.meta.url), `// Generated by scripts/gen-worldmap.mjs from Natural Earth land (public domain, via world-atlas 2.0.2, ISC). Do not edit.\n// Equirectangular, ${S} units per degree, latitude ${BOT}..${TOP}.\nexport const MAP_W = ${W};\nexport const MAP_H = ${H};\nexport const MAP_S = ${S};\nexport const MAP_TOP = ${TOP};\nexport const LAND = '${d}';\n`);
console.log('path bytes', d.length);
