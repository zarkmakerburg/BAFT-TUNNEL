    die "cannot retrieve the GitHub releases list"
  RELEASE_JSON="$(python3 -c '
import json, re, sys
stable = sys.argv[1] == "stable"
items = json.load(sys.stdin)
for item in items:
    tag = item.get("tag_name", "")
    if not item.get("draft") and (not stable or not item.get("prerelease")) and re.fullmatch(r"v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?", tag):
        print(json.dumps(item))
        break
' "$CHANNEL" <<<"$RELEASES_JSON")"
  if [[ -z "$RELEASE_JSON" ]]; then
    [[ "$CHANNEL" == "stable" ]] &&
      die "no stable release is published yet. To install a Preview (prerelease) build, re-run with --channel prerelease or --tag vX.Y.Z-rc.N"
    die "no published release found for the requested channel"
  fi
fi

RELEASE_META="$(python3 -c '
import json, sys
r = json.load(sys.stdin)
print(r.get("tag_name", ""))
print("true" if r.get("draft") else "false")
print("true" if r.get("prerelease") else "false")
' <<<"$RELEASE_JSON")"
TAG="$(printf '%s\n' "$RELEASE_META" | sed -n '1p')"
DRAFT="$(printf '%s\n' "$RELEASE_META" | sed -n '2p')"
PRERELEASE="$(printf '%s\n' "$RELEASE_META" | sed -n '3p')"
[[ "$TAG" =~ ^v[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]] || die "GitHub returned an invalid release tag"
[[ "$DRAFT" == "false" ]] || die "refusing to install a draft release"
# A pinned --tag is an explicit choice; only channel selection is gated here.
if [[ -z "$PINNED_TAG" && "$CHANNEL" == "stable" && "$PRERELEASE" != "false" ]]; then
  die "the selected release is a prerelease, not a stable release"
fi

NAME="baft-tunnel-$TAG-linux-x86_64"
BASE="https://github.com/$REPO/releases/download/$TAG"
ARCHIVE="$NAME.tar.gz"
echo "Release: $TAG"
[[ "$PRERELEASE" != "true" ]] || echo "Channel: Preview / prerelease"

echo "Downloading and verifying signed release artifacts..."
# Bootstrap a fixed, digest-pinned Cosign verifier; never trust a verifier
# downloaded from the same unsigned release being verified.
COSIGN_DEB="cosign_2.5.3_amd64.deb"
curl -fsSL --retry 3 "https://github.com/sigstore/cosign/releases/download/$COSIGN_VERSION/$COSIGN_DEB" -o "$TMP/$COSIGN_DEB"
printf '%s  %s\n' "$COSIGN_SHA256" "$TMP/$COSIGN_DEB" | sha256sum --check --status ||
  die "the pinned Cosign package failed its SHA-256 check"
mkdir "$TMP/cosign-root"
dpkg-deb -x "$TMP/$COSIGN_DEB" "$TMP/cosign-root"
# The Debian package ships /usr/bin/cosign as an absolute symlink to this file;
# invoking the symlink from the temporary extraction root would escape that root.
COSIGN_BIN="$TMP/cosign-root/usr/bin/cosign-linux-amd64"
[[ -x "$COSIGN_BIN" ]] || die "the verified Cosign package contains no executable at the pinned package path"

curl -fsSL --retry 3 "$BASE/$ARCHIVE" -o "$TMP/$ARCHIVE"
curl -fsSL --retry 3 "$BASE/SHA256SUMS" -o "$TMP/SHA256SUMS"
curl -fsSL --retry 3 "$BASE/SHA256SUMS.cosign.bundle" -o "$TMP/SHA256SUMS.cosign.bundle"
awk -v archive="$ARCHIVE" '$2 == archive && length($1) == 64 && $1 !~ /[^0-9a-f]/ { found++ } END { exit found != 1 }' "$TMP/SHA256SUMS" ||
  die "the signed checksum manifest does not contain exactly the requested release archive"

IDENTITY="https://github.com/$REPO/.github/workflows/release.yml@refs/tags/$TAG"
# Online first (Sigstore TUF supplies the current trust root). If that is unreachable, verify the same
# bundle with the same identity/issuer pins against the trust root pinned in this script, with no network.
# A bad signature fails both; there is no checksum-only fallback.
if "$COSIGN_BIN" verify-blob "$TMP/SHA256SUMS" --bundle "$TMP/SHA256SUMS.cosign.bundle" \
  --certificate-identity "$IDENTITY" \
  --certificate-oidc-issuer https://token.actions.githubusercontent.com 2>"$TMP/cosign-online.err"; then
  echo "Signature verified (Sigstore online trust root)."
else
  echo "Sigstore online trust root not reachable or verification failed; verifying with the pinned Sigstore trust root..."
  mkdir -m 0700 "$TMP/sigstore" "$TMP/sigstore/home"
  printf '%s\n' "$SIGSTORE_FULCIO_PEM" >"$TMP/sigstore/fulcio.pem"
  printf '%s\n' "$SIGSTORE_REKOR_PEM" >"$TMP/sigstore/rekor.pub"
  printf '%s\n' "$SIGSTORE_CTLOG_PEM" >"$TMP/sigstore/ctlog.pub"
  if ! HOME="$TMP/sigstore/home" SIGSTORE_ROOT_FILE="$TMP/sigstore/fulcio.pem" \
    SIGSTORE_REKOR_PUBLIC_KEY="$TMP/sigstore/rekor.pub" SIGSTORE_CT_LOG_PUBLIC_KEY_FILE="$TMP/sigstore/ctlog.pub" \
    "$COSIGN_BIN" verify-blob "$TMP/SHA256SUMS" --bundle "$TMP/SHA256SUMS.cosign.bundle" --offline \
      --certificate-identity "$IDENTITY" \
      --certificate-oidc-issuer https://token.actions.githubusercontent.com; then
    sed 's/^/  online: /' "$TMP/cosign-online.err" >&2
    die "release signature verification failed (online and with the pinned Sigstore trust root); nothing was installed"
  fi
  echo "Signature verified offline (pinned Sigstore trust root)."
fi
(
  cd "$TMP"
  sha256sum --ignore-missing --check SHA256SUMS
)

# Validate every tar member before extraction: only regular files/directories
# beneath the exact release root are accepted; links and special files are refused.
python3 - "$TMP/$ARCHIVE" "$NAME" <<'PYTAR'
import pathlib, sys, tarfile
archive, expected = sys.argv[1:]
with tarfile.open(archive, "r:gz") as tf:
    members = tf.getmembers()
    if not members:
        raise SystemExit("empty release archive")
    for m in members:
        p = pathlib.PurePosixPath(m.name)
        if p.is_absolute() or not p.parts or p.parts[0] != expected or ".." in p.parts:
            raise SystemExit(f"unsafe archive path: {m.name!r}")
        if not (m.isdir() or m.isfile()):
            raise SystemExit(f"unsupported archive entry type: {m.name!r}")
PYTAR

tar -xzf "$TMP/$ARCHIVE" -C "$TMP" --no-same-owner --no-same-permissions
PKG="$TMP/$NAME"
[[ -x "$PKG/baft-tunnel" && -x "$PKG/scripts/install.sh" ]] || die "verified package is missing required installer files"
"$PKG/baft-tunnel" --version >/dev/null 2>&1 || die "release binary failed its version check"
if (( VERIFY_ONLY == 0 && NO_HTTPS == 0 )) && [[ ! -f "$PKG/scripts/panel-https.sh" ]]; then
  [[ -z "$HTTPS_HOST" ]] || die "release $TAG predates HTTPS support (no scripts/panel-https.sh); use a newer --tag/--channel prerelease, or --no-https"
fi
if (( VERIFY_ONLY == 1 )); then
  echo "Verified signed BAFT-TUNNEL release $TAG and package layout; no installation performed."
  exit 0
fi

if [[ -n "$AGENT_LISTEN" ]]; then
  bash "$PKG/scripts/install.sh" --binary "$PKG/baft-tunnel" --register "$INSTANCE" --agent-listen "$AGENT_LISTEN" </dev/null
else
  bash "$PKG/scripts/install.sh" --binary "$PKG/baft-tunnel" --register "$INSTANCE" </dev/null
fi

echo
echo "BAFT-TUNNEL $TAG installed and verified for instance $INSTANCE."
HTTPS_OK=0
PANEL_LINK=""
if (( NO_HTTPS == 0 )) && [[ -f "$PKG/scripts/panel-https.sh" ]]; then
  HARGS=(--agent-listen "${AGENT_LISTEN:-127.0.0.1:18080}")
  if [[ -n "$HTTPS_HOST" ]]; then
    HARGS+=("--$HTTPS_KIND" "$HTTPS_HOST")
    [[ -z "$HTTPS_EMAIL" ]] || HARGS+=(--email "$HTTPS_EMAIL")
    (( HTTPS_SELF == 0 )) || HARGS+=(--self-signed)
  else
    HARGS+=(--interactive)
  fi
  if bash "$PKG/scripts/panel-https.sh" "${HARGS[@]}" </dev/null; then
    HTTPS_RC=0
  else
    HTTPS_RC=$?
  fi
  # Success is what panel-https.sh recorded, not only its exit code (an empty interactive answer exits 0).
  if (( HTTPS_RC == 0 )) && [[ -f /var/lib/baft-tunnel-https/state ]]; then
    PANEL_HOST="$(sed -n 's/^HOST=//p' /var/lib/baft-tunnel-https/state | head -n1)"
    PANEL_PORT="$(sed -n 's/^HTTPS_PORT=//p' /var/lib/baft-tunnel-https/state | head -n1)"
    if [[ -n "$PANEL_HOST" ]]; then
      [[ "$PANEL_HOST" == *:* ]] && PANEL_HOST="[$PANEL_HOST]"
      # Plain if, not "$(test && echo)": under set -e that assignment returns 1 on port 443 and
      # silently ended the installer before the summary (LAB run 43879430384).
      PANEL_LINK="https://$PANEL_HOST"
      if [[ -n "$PANEL_PORT" && "$PANEL_PORT" != 443 ]]; then PANEL_LINK+=":$PANEL_PORT"; fi
      PANEL_LINK+="/"
      if [[ -s /var/lib/baft-tunnel-https/gate ]]; then
        # The secret web path goes to a terminal only, like the password.
        if [[ -t 1 ]]; then PANEL_LINK+="$(tr -d '[:space:]' </var/lib/baft-tunnel-https/gate)/"
        else PANEL_LINK+="<web path>/ (web path: sudo cat /var/lib/baft-tunnel-https/gate)"; fi
      fi
      HTTPS_OK=1
    fi
  elif (( HTTPS_RC != 0 )); then
    echo "HTTPS setup FAILED (exit $HTTPS_RC; the reason is printed above) and was rolled back." >&2
    echo "BAFT-TUNNEL itself is installed; the panel stays loopback-only." >&2
    echo "Fix the reason, then retry: sudo bash /usr/local/lib/baft-tunnel/scripts/panel-https.sh --domain NAME (or --ip ADDRESS)" >&2
  fi
fi
echo
echo "The tunnel itself was not started. Set it up in the panel Wizard (supported tcp-tls path)."
if (( HTTPS_OK == 1 )); then
  echo "Panel (HTTPS): $PANEL_LINK   password (login token): sudo cat /var/lib/baft-tunnel-agent/token"
else
  echo "Panel (loopback only): ssh -L 18080:127.0.0.1:18080 HOST, open http://127.0.0.1:18080/ ; token: sudo cat /var/lib/baft-tunnel-agent/token"
fi
# Interactive menu (installed with the package) when a real terminal is attached. Ask first, so the
# menu's screen redraw never hides the panel link and login box printed above.
if (( NO_MENU == 0 )) && [[ -t 1 && -r /dev/tty ]] && command -v baft-tunnel >/dev/null 2>&1; then
  echo
  printf 'Press Enter to open the BAFT-TUNNEL menu, or type q and Enter to finish here: ' >/dev/tty
  MENU_ANSWER=""
  IFS= read -r MENU_ANSWER </dev/tty || MENU_ANSWER=q
  if [[ "${MENU_ANSWER,,}" != q* ]]; then
    baft-tunnel menu </dev/tty || true
    if (( HTTPS_OK == 1 )); then echo "Panel (HTTPS): $PANEL_LINK"; fi
  fi
fi
exit 0
}
