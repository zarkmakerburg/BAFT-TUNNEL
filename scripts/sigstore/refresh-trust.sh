#!/usr/bin/env bash
# Pinned Sigstore trust for quick-install.sh offline verification (ADR-0034).
#   refresh-trust.sh --check   the block embedded in scripts/quick-install.sh matches trusted_root.json (CI)
#   refresh-trust.sh --regen   regenerate the embedded block from the committed trusted_root.json
#   refresh-trust.sh --update  fetch the current trusted root through Sigstore's TUF (cosign initialize,
#                              signature-verified against the TUF root embedded in the pinned Cosign),
#                              write trusted_root.json and regenerate the embedded block
# Refresh when Sigstore rotates a Fulcio CA, Rekor or CT log key (announced on blog.sigstore.dev), and
# at least before the Fulcio root expires (see `--check` output). Review the diff like any trust change.
set -euo pipefail
DIR="$(cd "$(dirname "$0")" && pwd -P)"
ROOT_JSON="$DIR/trusted_root.json"
QI="$DIR/../quick-install.sh"
BEGIN='# BEGIN SIGSTORE TRUST (generated by scripts/sigstore/refresh-trust.sh; do not edit by hand)'
END='# END SIGSTORE TRUST'

render() {
  python3 -I - "$ROOT_JSON" <<'PY'
import base64, json, sys, textwrap
d = json.load(open(sys.argv[1]))
assert d.get("mediaType", "").startswith("application/vnd.dev.sigstore.trustedroot+json"), "not a Sigstore trusted root"
pem = lambda raw, kind: "-----BEGIN %s-----\n%s\n-----END %s-----" % (kind, "\n".join(textwrap.wrap(raw, 64)), kind)
for blob in [c["rawBytes"] for ca in d["certificateAuthorities"] for c in ca["certChain"]["certificates"]]:
    base64.b64decode(blob, validate=True)
fulcio = "\n".join(pem(c["rawBytes"], "CERTIFICATE") for ca in d["certificateAuthorities"] for c in ca["certChain"]["certificates"])
rekor = [t for t in d["tlogs"] if t["baseUrl"] == "https://rekor.sigstore.dev"]
assert len(rekor) == 1, "expected exactly one rekor.sigstore.dev key"
ct = sorted([t for t in d["ctlogs"] if "end" not in t["publicKey"].get("validFor", {})], key=lambda t: t["publicKey"]["validFor"]["start"])
assert ct, "no current CT log key"
print("SIGSTORE_FULCIO_PEM='%s'" % fulcio)
print("SIGSTORE_REKOR_PEM='%s'" % pem(rekor[0]["publicKey"]["rawBytes"], "PUBLIC KEY"))
print("SIGSTORE_CTLOG_PEM='%s'" % pem(ct[-1]["publicKey"]["rawBytes"], "PUBLIC KEY"))
PY
}
current_block() { awk -v b="$BEGIN" -v e="$END" '$0==b{f=1;next} $0==e{f=0} f' "$QI"; }

case "${1:-}" in
  --check)
    diff <(render) <(current_block) >/dev/null || { echo 'quick-install.sh Sigstore trust block is out of date: run scripts/sigstore/refresh-trust.sh --update' >&2; exit 1; }
    end="$(render | python3 -I -c 'import sys,subprocess,re
p=sys.stdin.read().split("SIGSTORE_REKOR_PEM")[0].split("=",1)[1].strip().strip("\x27")
certs=re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----",p,re.S)
ends=[subprocess.run(["openssl","x509","-noout","-enddate"],input=c.encode(),capture_output=True).stdout.decode().strip().split("=")[1] for c in certs]
print(ends[-1])')"
    echo "Sigstore trust block matches trusted_root.json (current Fulcio chain valid until: $end)" ;;
  --update)
    COSIGN="${COSIGN:-cosign}"
    h="$(mktemp -d)"; trap 'rm -rf "$h"' EXIT
    HOME="$h" "$COSIGN" initialize >/dev/null
    cp "$h/.sigstore/root/tuf-repo-cdn.sigstore.dev/targets/trusted_root.json" "$ROOT_JSON"
    "$0" --regen ;;
  --regen)
    python3 -I - "$QI" "$BEGIN" "$END" <(render) <<'PY'
import sys
qi, b, e, block = sys.argv[1], sys.argv[2], sys.argv[3], open(sys.argv[4]).read()
s = open(qi).read()
i, j = s.index(b + "\n") + len(b) + 1, s.index(e + "\n")
open(qi, "w").write(s[:i] + block + s[j:])
PY
    echo "regenerated the quick-install.sh trust block from trusted_root.json; review the diff" ;;
  *) echo "usage: $0 --check | --regen | --update" >&2; exit 2 ;;
esac
